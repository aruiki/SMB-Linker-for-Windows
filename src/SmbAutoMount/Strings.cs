    private static Dictionary<string, string>? _current;

    public static void SetLanguage(string setting)
    {
        var lang = setting is "ja" or "en" ? setting : CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;
        _current = lang == "ja" ? Ja : En;
    }

    public static string T(string key) =>
        (_current ?? En).TryGetValue(key, out var v) ? v : En.TryGetValue(key, out var e) ? e : key;

    public static string F(string key, params object[] args) => string.Format(T(key), args);

    public static string StateName(MountState s) => T("st." + s);

